/**
 * Compare models and prompt versions: one row per evals/runs/<model>/<variant> (baseline, v1, … with the prompt
 * version each holds), written to evals/runs/COMPARISON.md and printed.
 * Means are per case over its reps, then over cases (so a case with more reps doesn't weigh more).
 *
 *   npm run evals:compare
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { VARIANT_NAME } from "./lib/variants";

const RUNS = join(import.meta.dirname, "runs");
const COLUMNS = [
  ["pass", "Pass"],
  ["code_pass", "Code checks"],
  ["extraction", "Extraction"],
  ["tool_use", "Tool use"],
  ["booking", "Booking"],
  ["handoff", "Handoff"],
  ["no_invented_prices", "No invented prices"],
  ["turns_ok", "Turns OK"],
  ["language", "Language"],
  ["style", "Style"],
  ["answers", "Judge: answers"],
  ["grounded", "Judge: grounded"],
  ["professional", "Judge: professional"],
] as const;

interface Row {
  prompt_id: string;
  rep: number;
  prompt_version?: string;
  grade: Record<string, number>;
  cost_usd: number | null;
  latency_s: number;
  meta?: { turns?: unknown[]; agent_cost_usd?: number | null };
}

function caseMeans(rows: Row[], pick: (row: Row) => number | undefined): number[] {
  const byCase = new Map<string, number[]>();
  for (const row of rows) {
    const value = pick(row);
    if (value === undefined) continue;
    byCase.set(row.prompt_id, [...(byCase.get(row.prompt_id) ?? []), value]);
  }
  return [...byCase.values()].map((values) => values.reduce((a, b) => a + b, 0) / values.length);
}

const mean = (values: number[]) => values.reduce((a, b) => a + b, 0) / values.length;

const lines: string[] = [];
const isDir = (path: string) => existsSync(path) && statSync(path).isDirectory();
/** [model, variant] pairs that have results; the baseline first within each model. */
const runs = (existsSync(RUNS) ? readdirSync(RUNS) : [])
  .filter((model) => isDir(join(RUNS, model)))
  .flatMap((model) =>
    readdirSync(join(RUNS, model))
      .filter(
        (variant) =>
          VARIANT_NAME.test(variant) && existsSync(join(RUNS, model, variant, "results.jsonl")),
      )
      .sort((a, b) =>
        a === "baseline" ? -1 : b === "baseline" ? 1 : Number(a.slice(1)) - Number(b.slice(1)),
      )
      .map((variant) => [model, variant] as const),
  );
const header = [
  "Model",
  "Variant",
  "Prompt",
  "Cases × reps",
  ...COLUMNS.map(([, label]) => label),
  "Latency / turn",
  "Agent cost / case",
  "Errors",
];
lines.push(`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`);

for (const [model, variant] of runs) {
  const dir = join(RUNS, model, variant);
  const rows = readFileSync(join(dir, "results.jsonl"), "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l) as Row);
  const errorsFile = join(dir, "errors.jsonl");
  // Only (case, rep) pairs that never got a result: an error fixed by a later retry doesn't count.
  const scored = new Set(rows.map((row) => `${row.prompt_id}#${row.rep}`));
  const errors = existsSync(errorsFile)
    ? new Set(
        readFileSync(errorsFile, "utf8")
          .split("\n")
          .filter(Boolean)
          .map((line) => JSON.parse(line) as { prompt_id: string; rep: number })
          .map((error) => `${error.prompt_id}#${error.rep}`)
          .filter((key) => !scored.has(key)),
      ).size
    : 0;
  const cases = new Set(rows.map((row) => row.prompt_id)).size;
  const cells = COLUMNS.map(([id]) => {
    const values = caseMeans(rows, (row) => row.grade[id]);
    return values.length === 0 ? "—" : `${(mean(values) * 100).toFixed(0)}% (n=${values.length})`;
  });
  const turns = rows.reduce((sum, row) => sum + (row.meta?.turns?.length ?? 1), 0);
  const latency = rows.reduce((sum, row) => sum + row.latency_s, 0) / turns;
  const costs = caseMeans(rows, (row) =>
    typeof row.meta?.agent_cost_usd === "number" ? row.meta.agent_cost_usd : undefined,
  );
  lines.push(
    `| ${[model, variant, [...new Set(rows.map((row) => row.prompt_version ?? "?"))].join(", "), `${cases} × ${(rows.length / cases).toFixed(1)}`, ...cells, `${latency.toFixed(1)} s`, costs.length ? `$${mean(costs).toFixed(5)}` : "—", String(errors)].join(" | ")} |`,
  );
}

const out = [
  "# Model comparison (generated by `npm run evals:compare`)",
  "",
  "Per-case mean over reps, then mean over cases. Agent cost excludes the judge. Errors = (case, rep) pairs that",
  "never produced a scorable result (infra or judge failure); they are not counted in the scores.",
  "",
  ...lines,
  "",
].join("\n");
writeFileSync(join(RUNS, "COMPARISON.md"), out);
console.log(out);
