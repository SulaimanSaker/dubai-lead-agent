/**
 * Write evals/CASES.md: every case in one readable page, for human review (the cases are the ground truth,
 * so a person must read all of them). `npm run evals:cases`
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_NOW, loadCases, type EvalCase } from "./lib/cases";

const dir = import.meta.dirname;
const cases = loadCases(join(dir, "cases"));

function expectations(evalCase: EvalCase): string[] {
  const e = evalCase.expect;
  const lines: string[] = [];
  if (e.lead) lines.push(`Lead saved: \`${JSON.stringify(e.lead)}\``);
  if (e.leadUnknown) lines.push(`Must stay empty: ${e.leadUnknown.join(", ")}`);
  for (const call of e.toolCalls ?? []) {
    const args = call.args ? ` with \`${JSON.stringify(call.args)}\`` : "";
    const absent = call.argsAbsent ? `, without ${call.argsAbsent.join(", ")}` : "";
    lines.push(`Calls \`${call.name}\`${args}${absent}`);
  }
  if (e.forbiddenTools) lines.push(`Never calls: ${e.forbiddenTools.join(", ")}`);
  lines.push(
    `Viewing booked: **${e.viewingBooked ? "yes" : "no"}** · Handoff: **${e.handoff ? "yes" : "no"}**`,
  );
  lines.push(`Replies in: ${e.language === "ar" ? "Arabic" : "English"}`);
  return lines;
}

const fence = (text: string) => {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const marks = "`".repeat(longest + 1);
  return `${marks}text\n${text}\n${marks}`;
};

const out: string[] = [
  "# Eval cases (for review)",
  "",
  `Generated by \`npm run evals:cases\` from \`evals/cases/*.json\`. ${cases.length} cases. "Now" is ` +
    `${DEFAULT_NOW} (Mon 16 Nov 2026, 14:05 Dubai) unless a case says otherwise.`,
  "",
  "| # | Case | Category | Lang | Source | Booked | Handoff |",
  "| - | ---- | -------- | ---- | ------ | ------ | ------- |",
  ...cases.map(
    (c, i) =>
      `| ${i + 1} | [${c.id}](#${c.id}) | ${c.tags[0]} | ${c.tags[1]} | ${c.source.startsWith("real") ? "real" : "synthetic"} | ${c.expect.viewingBooked ? "yes" : "no"} | ${c.expect.handoff ? "yes" : "no"} |`,
  ),
  "",
];

for (const [i, c] of cases.entries()) {
  out.push(`## ${c.id}`, "", `${i + 1}. **${c.description}**  `, `Source: ${c.source}`);
  if (c.now) out.push(`Now: ${c.now}`);
  if (c.setup) out.push(`Before the chat: ${JSON.stringify(c.setup)}`);
  out.push("", "Buyer messages:", "");
  c.messages.forEach((message, n) => out.push(`${n + 1}.`, "", fence(message), ""));
  out.push("Expected:", "", ...expectations(c).map((line) => `- ${line}`), "");
}

writeFileSync(join(dir, "CASES.md"), out.join("\n"));
console.log(`Wrote evals/CASES.md (${cases.length} cases)`);
